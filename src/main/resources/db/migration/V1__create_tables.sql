CREATE TABLE TB_USUARIO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(120) NOT NULL,
    EMAIL VARCHAR2(160) NOT NULL UNIQUE,
    SENHA VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) NOT NULL
);

CREATE TABLE TB_RESIDUO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_RESIDUO VARCHAR2(80) NOT NULL,
    PESO_KG NUMBER(12,2) NOT NULL,
    DATA_REGISTRO DATE NOT NULL,
    STATUS_COLETA VARCHAR2(20) NOT NULL,
    IMPACTO_CO2_KG NUMBER(12,2) NOT NULL
);

CREATE TABLE TB_COLETA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATA_COLETA DATE NOT NULL,
    EMPRESA_RESPONSAVEL VARCHAR2(140) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    RESIDUO_ID NUMBER NOT NULL,
    CONSTRAINT FK_COLETA_RESIDUO FOREIGN KEY (RESIDUO_ID) REFERENCES TB_RESIDUO(ID)
);

CREATE TABLE TB_RELATORIO_AMBIENTAL (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TOTAL_RESIDUOS_KG NUMBER(12,2) NOT NULL,
    TOTAL_CO2_EVITADO_KG NUMBER(12,2) NOT NULL,
    DATA_GERACAO DATE NOT NULL
);
